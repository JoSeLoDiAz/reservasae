async function main() {
  let creados = 0;
  let repetidos = 0;

  for (const [nit, dv, razonSocial] of BANCO) {
    const antes = await prisma.institucion.findUnique({
      where: { nit_razonSocial: { nit, razonSocial } },
    });
    if (antes) {
      repetidos += 1;
      continue;
    }

    await prisma.institucion.create({
      data: { nit, razonSocial, digitoDeclarado: dv, fuente: 'CARGA' },
    });
    creados += 1;
  }

  // los que declaran un DV que la DIAN no da
  const discrepan = BANCO.filter(
    ([nit, dv]) => dv !== null && calcularDigitoVerificacion(nit) !== dv,
  );

  // los que amparan a mas de una institucion
  const porNit = new Map<string, number>();
  for (const [nit] of BANCO) porNit.set(nit, (porNit.get(nit) ?? 0) + 1);
  const agrupados = [...porNit.entries()].filter(([, n]) => n > 1);

  console.log(`\n  ${creados} instituciones cargadas, ${repetidos} ya estaban.`);
  console.log(`  ${agrupados.length} NIT amparan a más de una institución.`);

  if (discrepan.length) {
    console.log(`\n  Ojo: ${discrepan.length} traen un DV que no cuadra con la DIAN:`);
    for (const [nit, dv, nombre] of discrepan) {
      console.log(`    ${nit} declara ${dv}, calculado ${calcularDigitoVerificacion(nit)} · ${nombre}`);
    }
  }
}

main()
  .catch((e) => {
    console.error(e);
    process.exitCode = 1;
  })
  .finally(() => prisma.$disconnect());
